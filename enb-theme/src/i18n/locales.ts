export type MessageKey = keyof (typeof MESSAGES)["zh-CN"];

function detectInitialLocale(): LocaleCode {
  try {
    const saved = localStorage.getItem("i18nextLng") || localStorage.getItem("enb-locale");
    if (saved) {
      if (saved.startsWith("zh-TW") || saved.startsWith("zh_TW") || saved.startsWith("zh-HK")) return "zh-TW";
      if (saved.startsWith("zh")) return "zh-CN";
      if (saved.startsWith("ja")) return "ja-JP";
      if (saved.startsWith("en")) return "en-US";
    }
    const nav = navigator.language || "";
    if (nav.startsWith("zh-TW") || nav.startsWith("zh-HK")) return "zh-TW";
    if (nav.startsWith("zh")) return "zh-CN";
    if (nav.startsWith("ja")) return "ja-JP";
    if (nav.startsWith("en")) return "en-US";
  } catch {
    // ignore
  }
  return "zh-CN";
}

interface I18nContextValue {
  locale: LocaleCode;
  setLocale: (code: LocaleCode) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: "zh-CN",
  setLocale: () => undefined,
  t: (key) => key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleCode>(detectInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      localStorage.setItem("enb-locale", locale);
      localStorage.setItem("i18nextLng", locale);
      document.cookie = `language=${encodeURIComponent(locale)};path=/;max-age=31536000;SameSite=Lax`;
    } catch {
      // ignore
    }
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => {
    const dict = MESSAGES[locale] ?? MESSAGES["zh-CN"];
    return {
      locale,
      setLocale: setLocaleState,
      t: (key, vars) => {
        let text: string = dict[key] ?? MESSAGES["zh-CN"][key] ?? key;
        if (vars) {
          for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
          }
        }
        return text;
      },
    };
  }, [locale]);

  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  return useContext(I18nContext);
}
