// Regenerates src/theme/materialSymbols.generated.ts from Material Symbols Rounded (Apache-2.0).
// Usage: node script/generate-material-symbols.mjs <path-to-@material-symbols/svg-400/rounded>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const manifest = JSON.parse(readFileSync("script/material-symbols.json", "utf8"));
const sourceDir = process.argv[2];
if (!sourceDir) {
  throw new Error("Pass the @material-symbols/svg-400 rounded directory as the first argument.");
}

const readPath = (file) => {
  const svg = readFileSync(path.join(sourceDir, file), "utf8");
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${file}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)];
  if (paths.length !== 1) throw new Error(`${file}: expected exactly one path`);
  return paths[0][1];
};

const lines = Object.entries(manifest.icons)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, { symbol, mode }]) => {
    const outline = mode === "fill" ? readPath(`${symbol}-fill.svg`) : readPath(`${symbol}.svg`);
    const fill = mode === "toggle" ? readPath(`${symbol}-fill.svg`) : undefined;
    return `  ${name}: ${JSON.stringify(fill ? { outline, fill } : { outline })},`;
  });

const output = `// Generated by script/generate-material-symbols.mjs. Do not edit by hand.
// Source: ${manifest.package}@${manifest.version} (${manifest.style}), Apache License 2.0, Google LLC.
export type MaterialSymbolPaths = { outline: string; fill?: string };

export const MATERIAL_SYMBOLS = {
${lines.join("\n")}
} as const satisfies Record<string, MaterialSymbolPaths>;

export type MaterialSymbolName = keyof typeof MATERIAL_SYMBOLS;
`;

writeFileSync("src/theme/materialSymbols.generated.ts", output);
console.log(`Wrote ${lines.length} Material Symbols Rounded icons.`);
